// Builds the HEAL letter paths for the I1 hero (BUILD-PLAYBOOK §5).
// Reads Host Grotesk Medium (scripts/fonts/, not shipped), sets "HEAL" at
// tracking -0.05em and writes src/components/sections/home/heal-letters.ts.
// Run once: npm run build:letters
import { readFileSync, writeFileSync } from "node:fs";
import opentype from "opentype.js";

const FONT = "scripts/fonts/HostGrotesk-Medium.ttf";
const OUT = "src/components/sections/home/heal-letters.ts";
const WORD = "HEAL";
const SIZE = 1000; // font units == px at this size, keeps numbers readable
const TRACKING = -0.05;

const buf = readFileSync(FONT);
const font = opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));
const scale = SIZE / font.unitsPerEm;
const ascender = font.ascender * scale;

let x = 0;
const letters = [];
const glyphs = font.stringToGlyphs(WORD);
glyphs.forEach((glyph, i) => {
  const path = glyph.getPath(x, ascender, SIZE);
  const bb = path.getBoundingBox();
  letters.push({ char: WORD[i], d: path.toPathData(2), bbox: bb });
  let advance = glyph.advanceWidth * scale;
  if (i < glyphs.length - 1) advance += font.getKerningValue(glyph, glyphs[i + 1]) * scale;
  x += advance + TRACKING * SIZE;
});

// Tight viewBox around the ink.
const minX = Math.min(...letters.map((l) => l.bbox.x1));
const minY = Math.min(...letters.map((l) => l.bbox.y1));
const maxX = Math.max(...letters.map((l) => l.bbox.x2));
const maxY = Math.max(...letters.map((l) => l.bbox.y2));
const r = (n) => Math.round(n * 100) / 100;

// Stem width from the H: its first contour is a full-height vertical stem.
const hFirst = font.charToGlyph("H").getPath(0, ascender, SIZE).toPathData(2).split("M")[1];
const xs = hFirst.split(/[ML]/).filter(Boolean).map((pt) => Number(pt.trim().split(" ")[0]));
const stemWidth = r(Math.max(...xs) - Math.min(...xs));

const data = {
  stemWidth,
  viewBox: { x: r(minX), y: r(minY), width: r(maxX - minX), height: r(maxY - minY) },
  letters: letters.map((l) => ({
    char: l.char,
    d: l.d,
    bbox: { x: r(l.bbox.x1), y: r(l.bbox.y1), width: r(l.bbox.x2 - l.bbox.x1), height: r(l.bbox.y2 - l.bbox.y1) },
  })),
};

const file = `// Generated by scripts/build-heal-letters.mjs from Host Grotesk Medium.
// Do not edit by hand: rerun \`npm run build:letters\`.

export type HealLetter = "H" | "E" | "A" | "L";

export const healLetters = ${JSON.stringify(data, null, 2)} as const;
`;
writeFileSync(OUT, file);

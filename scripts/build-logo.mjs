// Builds everything logo-related from the supplied vector logo
// (public/brand/healmedllc-sg.svg): typed paths for <Logo>, app icons, and a
// white SVG for the share image. Run: npm run build:logo
import { readFileSync, writeFileSync } from "node:fs";
import sharp from "sharp";

const SRC = "public/brand/healmedllc-sg.svg";
const svg = readFileSync(SRC, "utf8");
const d = [...svg.matchAll(/<path[^>]*\sd="([^"]+)"/g)].map((m) => m[1]);
if (d.length !== 15) throw new Error(`expected 15 paths, found ${d.length}`);

// Path order in the source: 0 = H circle mark, 1-4 = H E A L, 5-14 = MEDICAL LLC.
const mark = d[0];
const word = d.slice(1, 5);
const sub = d.slice(5);
// Measured bounds (getBBox): mark 32.1,172.6 → 185.9,325.9; all → 436.9.
const viewBox = { full: "32 172 405 154", mark: "32 172 154 154" };

writeFileSync(
  "src/components/ui/logo-paths.ts",
  `// Generated by scripts/build-logo.mjs from public/brand/healmedllc-sg.svg.
// Do not edit by hand: rerun \`npm run build:logo\`.

export const logoPaths = ${JSON.stringify({ viewBox, mark, word, sub }, null, 2)} as const;
`,
);

const markSvg = (fg, bg, size, pad) => {
  const s = 154, scale = (size - pad * 2) / s;
  return Buffer.from(`<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 ${size} ${size}">
${bg ? `<rect width="${size}" height="${size}" fill="${bg}"/>` : ""}
<g transform="translate(${pad} ${pad}) scale(${scale}) translate(-32 -172)"><path d="${mark}" fill="${fg}"/></g></svg>`);
};

await sharp(markSvg("#F5F5FE", "#6556B8", 512, 72)).png().toFile("src/app/icon.png");
await sharp(markSvg("#F5F5FE", "#6556B8", 180, 26)).png().toFile("src/app/apple-icon.png");

const full = (fill) => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox.full}" width="405" height="154">${d
  .map((p) => `<path d="${p}" fill="${fill}"/>`)
  .join("")}</svg>`;
writeFileSync("public/brand/heal-logo-white.svg", full("#FFFFFF"));
console.log("logo paths, icons and white SVG written");
